import { test } from 'node:test';
import assert from 'node:assert/strict';
import { generate } from './gen-ui-spec-tests.mjs';

const spec = {
  image: 'home.png', cssWidth: 1063, cssHeight: 1052,
  rows: [
    { id: 'page', parent: null, role: 'page (canvas)', text: '', x: 0, y: 0, w: '1063', h: 1052, padding: null, layout: 'column, mixed', gap: null, tol: '' },
    { id: 'g1', parent: 'page', role: 'group (inferred)', text: '', x: 46, y: 24, w: '954', h: 40, padding: null, layout: 'row, center', gap: 96, tol: 'derived' },
    { id: 1, parent: 'g1', role: 'heading', text: '[T1]', x: 46, y: 28, w: '76', h: 28, padding: null, layout: null, gap: null, tol: 4 },
    { id: 2, parent: 'g1', role: 'button', text: 'Caf' + String.fromCharCode(233) + ' menu', x: 868, y: 24, w: '132', h: 40, padding: [8, null, 8, 12], layout: 'row, center', gap: 8, tol: 2 },
  ],
};
const opts = { route: '/home', attr: 'data-ui-id', slack: 1, source: 'docs/design/specs/home.spec.json' };

test('output is plain ASCII with no trailing whitespace and one trailing newline', () => {
  const out = generate(spec, opts);
  assert.equal(/[^\x00-\x7f]/.test(out), false);
  assert.equal(/[ \t]+$/m.test(out), false);
  assert.equal(out.endsWith('\n'), true);
  assert.equal(out.endsWith('\n\n'), false);
});

test('non-ASCII copy is escaped, not written raw', () => {
  const out = generate(spec, opts);
  assert.match(out, /Caf\\u00e9 menu/);
});

test('header carries the route, canvas, attribute and slack', () => {
  const out = generate(spec, opts);
  assert.match(out, /const ROUTE = "\/home";/);
  assert.match(out, /const CANVAS = \{ width: 1063, height: 1052 \};/);
  assert.match(out, /const ATTR = "data-ui-id";/);
  assert.match(out, /const SLACK = 1;/);
  assert.match(out, /GENERATED by scripts\/gen-ui-spec-tests\.mjs from docs\/design\/specs\/home\.spec\.json/);
});

test('every spec row is embedded, in order', () => {
  const out = generate(spec, opts);
  const ids = [...out.matchAll(/^ {2}\{"id":("?[\w]+"?)/gm)].map((m) => m[1]);
  assert.deepEqual(ids, ['"page"', '"g1"', '1', '2']);
});

test('redacted placeholders stay placeholders without a textmap, and are filled with one', () => {
  assert.match(generate(spec, opts), /"text":"\[T1\]"/);
  const filled = generate(spec, { ...opts, textmap: { T1: 'Welcome back' } });
  assert.match(filled, /"text":"Welcome back"/);
  assert.doesNotMatch(filled, /\[T1\]"/);
});

test('generation is deterministic', () => {
  assert.equal(generate(spec, opts), generate(spec, opts));
});

test('the runtime skips the page row and treats derived groups as optional', () => {
  const out = generate(spec, opts);
  assert.match(out, /if \(r\.id === 'page'\) continue;/);
  assert.match(out, /optional inferred group has no element/);
});
